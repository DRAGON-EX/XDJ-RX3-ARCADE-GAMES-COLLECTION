"""Build shared scrolling credits and the portable browser scene renderer."""
import json, subprocess, unicodedata
from pathlib import Path
catalog=json.loads(Path('content/music-library.json').read_text())
def clean(s):
    return unicodedata.normalize('NFKD',s.replace('’', "'").replace('—', '-')).encode('ascii','ignore').decode().upper()
rows=[('MADE FOR THE LOVE OF IT',3,0),('DJ DRAGON-X',5,1),('CODE - CURIOSITY - CATS',2,0),('',2,0),('MUSIC AND SOUND',3,1)]
for t in catalog:
    rows += [(clean('Secret Song' if t.get('lock_message') else t['title']),2,0),(clean(t['artist']),2,1),('',1,0)]
rows += [('RETRO GAME BACKGROUND MUSIC',2,0),('OMARCREATIVE - FAREWELL MUSIC',2,1),('',1,0),('WELCOME SOUND',2,0),('MIXKIT - WINNING AN EXTRA BONUS',2,1),('',1,0),('AND YOU',10,1),('THANKS FOR MAKING ROOM FOR PLAY',2,0)]
header='/* Generated by tools/build_credits.py. */\nstruct credits_line { const char *value; int scale,accent; };\nstatic const struct credits_line credits_lines[]={\n'
header+=''.join('{'+json.dumps(s)+f',{z},{a}'+'},\n' for s,z,a in rows)+'};\n'
# The scene lasts exactly two decoded soundtrack passes (44,100 output frames/s).
secret=next(t for t in catalog if t.get('unlock')=='credits')
pcm=subprocess.check_output(['ffmpeg','-v','error','-i',secret['source'],'-ar','22050','-ac','1','-f','s16le','-'])
duration_ms=round(2*len(pcm)*1000/44100)
assert duration_ms>100000
shoutouts=json.loads(Path('content/credits-shoutouts.json').read_text())
artists=shoutouts['artists']
quote=shoutouts['gear_thanks']
prefix='Thank you, Pioneer DJ / AlphaTheta. '
suffix=' Priceless.'
assert quote.startswith(prefix) and quote.endswith(suffix)
quote_lines=[
    "YOUR GEAR IS OVERPRICED AS FUCK -",
    "IF I HAVE TO REFINANCE MY HOUSE",
    "TO AFFORD A DJ SETUP, THE FUCKING",
    "NIGHTCLUB HAD BETTER BE INCLUDED.",
    "BUT THE MOMENTS I'VE HAD",
    "BEHIND THOSE DECKS?",
]
assert ' '.join(quote_lines)==clean(quote[len(prefix):-len(suffix)])
assert len(quote_lines)<=7
header+='static const char*credits_gear_thanks[]={'+','.join(json.dumps(line) for line in quote_lines)+'};\n'
code_lines=[
    "PIONEER TOOK MY MONEY.",
    "CHATGPT & CODEX CAME BACK",
    "FOR WHATEVER WAS LEFT.",
    "BUT ONE GAVE ME UNFORGETTABLE",
    "NIGHTS BEHIND THE DECKS,",
    "AND THE OTHERS SAVED ME COUNTLESS",
    "NIGHTS FIGHTING WITH CODE",
    "FOR THIS PROJECT.",
    "FUCK THE PRICES.",
    "LOVE WHAT YOU HELPED ME DO.",
]
assert ' '.join(code_lines)==clean(shoutouts['code_thanks'])
assert max(map(len,code_lines))*18<=680
header+='static const char*credits_code_thanks[]={'+','.join(json.dumps(line) for line in code_lines)+'};\n'
header+=f'#define CREDITS_DURATION_MS {duration_ms}u\n#define CREDITS_SCROLL_END_MS 54000u\n#define CREDITS_DJ_END_MS {duration_ms-54000}u\n#define CREDITS_GEAR_END_MS {duration_ms-36000}u\n#define CREDITS_CODE_END_MS {duration_ms-18000}u\n#define CREDITS_GAG_END_MS {duration_ms-10000}u\n'
header+='static const char*credits_djs[]={'+','.join(json.dumps(clean(a)) for a in artists)+'};\n'
Path('shared/credits_data.h').write_text(header)
# The shared cat and dragon atlases need 67 WASM pages including the framebuffer.
subprocess.run(['clang','--target=wasm32','-O2','-ffreestanding','-fno-builtin','-nostdlib','-Wl,--no-entry','-Wl,--export=rescue_locked_frame','-Wl,--export=credits_locked_frame','-Wl,--export=credits_frame','-Wl,--export=credits_confirm_frame','-Wl,--export=credits_buffer','-Wl,--export=credits_duration','-Wl,--export=credits_code_start','-Wl,--export=credits_code_span','-Wl,--export-memory','-Wl,--initial-memory=4390912','src/credits_preview.c','-o','assets/credits-scene.wasm'],check=True)
print('Credits:',len(rows),'scrolling lines,',len(artists),'DJs, two song passes:',duration_ms,'ms')
