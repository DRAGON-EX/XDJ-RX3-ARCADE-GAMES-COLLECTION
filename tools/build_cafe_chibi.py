"""Pack the selected chibi animation sheets for the shared ARM/WASM renderer.

Image generation supplies the drawings. This build step extracts the eight
cells, aligns their feet, scales with nearest-neighbour and stores colour runs.
Full-resolution PNGs are never decoded or loaded by the game.
"""
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SOURCES = sorted((ROOT / 'assets/cats/chibi').glob('[0-9][0-9]-*.png'))
W, H, FRAMES, COLORS = 80, 96, 8, 64
assert len(SOURCES) == 11, 'Need all eleven cat animation sheets'
palettes, offsets, spans = [], [0], []
preview = ROOT / 'work/chibi-frames'
preview.mkdir(parents=True, exist_ok=True)

for cat, source in enumerate(SOURCES):
    assert int(source.name[:2]) == cat
    sw, sh = map(int, subprocess.check_output(['magick', 'identify', '-format', '%w %h', str(source)]).split())
    assert sw >= 800 and sh >= 400
    cells, boxes = [], []
    for frame in range(FRAMES):
        # Generated PNGs can have an odd total size; divide the grid at rounded
        # boundaries rather than dropping the final column or row of pixels.
        x0, x1 = round(frame % 4 * sw / 4), round((frame % 4 + 1) * sw / 4)
        y0, y1 = round(frame // 4 * sh / 2), round((frame // 4 + 1) * sh / 2)
        cw, ch = x1 - x0, y1 - y0
        cell = f'{cw}x{ch}+{x0}+{y0}'
        cells.append(cell)
        bounds = subprocess.check_output(['magick', str(source), '-crop', cell, '+repage',
            '-alpha', 'extract', '-threshold', '75%', '-format', '%@', 'info:']).decode()
        match = re.fullmatch(r'(\d+)x(\d+)\+(\d+)\+(\d+)', bounds)
        assert match, (source, frame, bounds)
        bw, bh, bx, by = map(int, match.groups())
        assert bw > cw // 4 and bh > ch // 4, (source, frame, bounds)
        boxes.append((bw, bh, bx, by))
    factor = min((W - 4) / max(b[0] for b in boxes), (H - 4) / max(b[1] for b in boxes))
    for frame, (bw, bh, bx, by) in enumerate(boxes):
        rw, rh = max(1, round(bw * factor)), max(1, round(bh * factor))
        # Binary alpha removes the nearly transparent fringe around generated
        # drawings before palette packing, avoiding dark boxes on the cafe wall.
        args = ['magick', str(source), '-crop', cells[frame], '+repage',
            '-crop', f'{bw}x{bh}+{bx}+{by}', '+repage',
            '-channel', 'A', '-threshold', '75%', '+channel',
            '-filter', 'point', '-resize', f'{rw}x{rh}!',
            '-background', 'none', '-gravity', 'south', '-extent', f'{W}x{H}',
            '+dither', '-colors', str(COLORS), '-depth', '8']
        rgba = subprocess.check_output(args + ['rgba:-'])
        assert len(rgba) == W * H * 4
        palette, lookup, pixels = [0], {}, []
        for i in range(0, len(rgba), 4):
            r, g, b, a = rgba[i:i + 4]
            if a < 192:
                pixels.append(0)
                continue
            rgb = (r << 16) | (g << 8) | b
            if rgb not in lookup:
                lookup[rgb] = len(palette)
                palette.append(rgb)
            pixels.append(lookup[rgb])
        assert len(palette) <= COLORS, (source, frame, len(palette))
        palettes.append(palette + [0] * (COLORS - len(palette)))
        for y in range(H):
            x = 0
            while x < W:
                c, end = pixels[y * W + x], x + 1
                while end < W and pixels[y * W + end] == c:
                    end += 1
                if c:
                    spans.append((x, y, end - x, c))
                x = end
        offsets.append(len(spans))
        subprocess.run(args + [str(preview / f'{cat:02}-{frame}.png')], check=True)
    print(source.name, 'packed eight aligned animation frames')

packed = len(spans) * 4 + len(palettes) * COLORS * 4 + len(offsets) * 4
assert packed < 1024 * 1024, f'Cafe artwork exceeded 1 MiB: {packed}'
out = '/* Generated by tools/build_cafe_chibi.py; original Imagegen artwork. */\n'
out += '#define CAFE_CHIBI_COUNT 11\n#define CAFE_CHIBI_FRAMES 8\n#define CAFE_CHIBI_W 80\n#define CAFE_CHIBI_H 96\n'
out += 'static const unsigned cafe_chibi_palette[88][64]={\n'
out += ''.join('{' + ','.join(hex(c) for c in p) + '},\n' for p in palettes) + '};\n'
out += 'static const unsigned cafe_chibi_offsets[89]={' + ','.join(map(str, offsets)) + '};\n'
out += 'static const unsigned char cafe_chibi_spans[][4]={\n'
out += ''.join('{' + ','.join(map(str, span)) + '},\n' for span in spans) + '};\n'
(ROOT / 'shared/cafe_chibi_atlas.h').write_text(out)
print(f'Chibi animation atlas: {len(palettes)} frames, {packed:,} bytes, no runtime allocation')
