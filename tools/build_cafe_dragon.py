"""Extract eight reference-based dragon poses into a read-only indexed atlas."""
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
source = ROOT / 'assets/cafe/dragon-chibi-ref-v2.png'
W, H, COLORS = 128, 128, 96
sw, sh = map(int, subprocess.check_output(['magick', 'identify', '-format', '%w %h', str(source)]).split())
cells, boxes, palettes, frames = [], [], [], []
for frame in range(8):
    x0, x1 = round(frame % 4 * sw / 4), round((frame % 4 + 1) * sw / 4)
    y0, y1 = round(frame // 4 * sh / 2), round((frame // 4 + 1) * sh / 2)
    cell = f'{x1-x0}x{y1-y0}+{x0}+{y0}'
    cells.append(cell)
    bounds = subprocess.check_output(['magick', str(source), '-crop', cell, '+repage',
        '-alpha', 'extract', '-threshold', '75%', '-format', '%@', 'info:']).decode()
    match = re.fullmatch(r'(\d+)x(\d+)\+(\d+)\+(\d+)', bounds)
    assert match, bounds
    boxes.append(tuple(map(int, match.groups())))
factor = min(120 / max(b[0] for b in boxes), 120 / max(b[1] for b in boxes))
for frame, (bw, bh, bx, by) in enumerate(boxes):
    rw, rh = max(1, round(bw * factor)), max(1, round(bh * factor))
    args = ['magick', str(source), '-crop', cells[frame], '+repage',
        '-crop', f'{bw}x{bh}+{bx}+{by}', '+repage', '-channel', 'A', '-threshold', '75%', '+channel',
        '-filter', 'point', '-resize', f'{rw}x{rh}!', '-background', 'none',
        '-gravity', 'south', '-extent', f'{W}x{H}', '+dither', '-colors', str(COLORS), '-depth', '8']
    rgba = subprocess.check_output(args + ['rgba:-'])
    assert len(rgba) == W * H * 4
    palette, lookup, pixels = [0], {}, []
    for i in range(0, len(rgba), 4):
        r, g, b, a = rgba[i:i+4]
        if a < 192:
            pixels.append(0)
            continue
        rgb = r << 16 | g << 8 | b
        if rgb not in lookup:
            lookup[rgb] = len(palette)
            palette.append(rgb)
        pixels.append(lookup[rgb])
    assert len(palette) <= COLORS
    palettes.append(palette + [0] * (COLORS - len(palette)))
    frames.append(pixels)
    subprocess.run(args + [str(ROOT / f'work/cafe-dragon-frame-{frame}.png')], check=True)
size = len(frames) * W * H + len(palettes) * COLORS * 4
assert size < 150 * 1024
out = '/* Generated by tools/build_cafe_dragon.py; original reference-based Imagegen art. */\n'
out += 'static const unsigned cafe_dragon_palette[8][96]={\n'
out += ''.join('{' + ','.join(hex(c) for c in p) + '},\n' for p in palettes) + '};\n'
out += 'static const unsigned char cafe_dragon_pixels[8][128*128]={\n'
for pixels in frames:
    out += '{\n' + ''.join(','.join(map(str, pixels[y*W:(y+1)*W])) + ',\n' for y in range(H)) + '},\n'
out += '};\n'
(ROOT / 'shared/cafe_dragon_atlas.h').write_text(out)
print(f'Cafe dragon: eight poses, {size:,} bytes, no runtime allocation')
