"""Pack the cafe room into a small read-only 256-colour pixel backdrop.

Imagegen supplies the artwork. This build step only resizes and indexes it;
the RX3 never decodes the large source PNG or allocates a background texture.
"""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
W, H = 596, 253
source = ROOT / 'assets/cafe/midnight-room-v1.png'
args = ['magick', str(source), '-alpha', 'off', '-filter', 'point',
        '-resize', f'{W}x{H}!', '+dither', '-colors', '256', '-depth', '8']
rgb = subprocess.check_output(args + ['rgb:-'])
assert len(rgb) == W * H * 3
palette, lookup, pixels = [], {}, []
for offset in range(0, len(rgb), 3):
    r, g, b = rgb[offset:offset + 3]
    color = (r << 16) | (g << 8) | b
    if color not in lookup:
        lookup[color] = len(palette)
        palette.append(color)
    pixels.append(lookup[color])
assert len(palette) <= 256
out = '/* Generated by tools/build_cafe_room.py; original Imagegen artwork. */\n'
out += f'#define CAFE_ROOM_W {W}\n#define CAFE_ROOM_H {H}\n'
out += 'static const unsigned cafe_room_palette[256]={'
out += ','.join(hex(c) for c in palette + [0] * (256 - len(palette))) + '};\n'
out += 'static const unsigned char cafe_room_pixels[CAFE_ROOM_W*CAFE_ROOM_H]={\n'
out += ''.join(','.join(map(str, pixels[y*W:(y+1)*W])) + ',\n' for y in range(H)) + '};\n'
(ROOT / 'shared/cafe_room_art.h').write_text(out)
subprocess.run(args + [str(ROOT / 'work/cafe-room-packed.png')], check=True)
print(f'Cafe room: {W}x{H}, {len(pixels) + 1024:,} bytes, no runtime allocation')
