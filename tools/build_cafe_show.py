"""Bake good.mp3's music envelope into small, shared screen/LED show cues.

Only the build machine analyses audio; RX3 playback uses integer table lookups.
The 128 BPM grid is fitted to bass onsets in the two main drops. Sections are
arranged in eight-bar phrases, with a separate final fade matching the source.
"""
from pathlib import Path
import array
import hashlib
import json
import math
import subprocess
import zipfile

SOURCE = Path('assets/music/cafe-good.mp3')
source_bytes = SOURCE.read_bytes() if SOURCE.exists() else zipfile.ZipFile('assets/music/good.zip').read('good.mp3', pwd=b'good')
raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', 'pipe:0',
                               '-ar', '8000', '-ac', '1', '-f', 'f32le', '-'], input=source_bytes)
samples = array.array('f'); samples.frombytes(raw)
features = []
low = mid = 0.0
for start in range(0, len(samples), 160):
    total = bass = high = 0.0
    for value in samples[start:start + 160]:
        low += .075 * (value - low)
        mid += .6 * (value - mid)
        total += value * value; bass += low * low; high += (value-mid)**2
    features.append([math.sqrt(v / 160) for v in (total, bass, high)])
onsets = [max(0, f[1] - sum(p[1] for p in features[max(0,i-10):i]) / min(10,i))
          if i else 0 for i, f in enumerate(features)]
limits = [sorted(f[c] for f in features)[int(len(features)*.97)] for c in range(3)]
onset_limit = sorted(onsets)[int(len(onsets)*.97)] or 1
duration = math.ceil(len(samples) / 8)
rows = []
release = [0.0]*4
for ms in range(0, duration+50, 50):
    points = range(ms//20, min(len(features), (ms+50)//20+1))
    values = [max((features[i][c] for i in points), default=0)/limits[c] for c in range(3)]
    values.append(max((onsets[i] for i in points), default=0)/onset_limit)
    for c, value in enumerate(values):
        release[c] = max(min(1, value), release[c] * (.64 if c==3 else .8))
    rows.append([round(value*255) for value in release])
# ID: 0 intro/outro, 1 groove, 2 build, 3 drop, 4 breakdown, 5 finale.
sections = [(0,0,'Opening'), (15148,1,'First groove'), (30148,2,'First build'),
            (45148,3,'First drop'), (60148,4,'Breathing room'), (75148,1,'Second groove'),
            (90148,2,'Second build'), (105148,3,'Main drop'), (135148,1,'Last groove'),
            (150148,5,'Finale'), (165148,0,'Afterglow')]
header = ['#ifndef RX3_CAFE_SHOW_H', '#define RX3_CAFE_SHOW_H',
          '/* Generated by tools/build_cafe_show.py from cafe-good.mp3. */',
          f'#define CAFE_SHOW_DURATION_MS {duration}u', '#define CAFE_SHOW_BPM 128u',
          'struct cafe_show_frame { unsigned ms,beat,phase,energy,bass,high,hit,section; };',
          f'static const unsigned char cafe_show_envelope[{len(rows)}][4]={{']
header.extend(' {'+','.join(map(str,row))+'},' for row in rows)
header += ['};', 'static struct cafe_show_frame cafe_show_frame(unsigned ms){',
           ' struct cafe_show_frame f={0};f.ms=ms;',
           ' if(ms>=CAFE_SHOW_DURATION_MS)return f;',
           ' unsigned clock=ms>148?(ms-148)*CAFE_SHOW_BPM:0;',
           ' f.beat=clock/60000;f.phase=(clock%60000)*256/60000;',
           ' unsigned i=ms/50,t=ms%50;',
           ' const unsigned char*a=cafe_show_envelope[i],*b=cafe_show_envelope[i+1];',
           ' f.energy=(a[0]*(50-t)+b[0]*t)/50;f.bass=(a[1]*(50-t)+b[1]*t)/50;',
           ' f.high=(a[2]*(50-t)+b[2]*t)/50;f.hit=(a[3]*(50-t)+b[3]*t)/50;']
for time, section, _ in sections:
    
    if time: header.append(f' if(ms>={time})f.section={section};')
header += [' return f;', '}', '#endif', '']
Path('shared/cafe_show.h').write_text('\n'.join(header))
Path('content/cafe-show.json').write_text(json.dumps({
    'source': str(SOURCE), 'sha256': hashlib.sha256(source_bytes).hexdigest(),
    'duration_ms': duration, 'bpm':128, 'beat_offset_ms':148, 'cue_interval_ms':50,
    'sections':[{'ms':t,'section':s,'name':name} for t,s,name in sections],
    'notes':'Grid estimated from bass onsets; envelopes extracted from this exact recording.'
}, indent=2)+'\n')
print(f'Café lightshow: {duration/1000:.2f}s, 128 BPM, {len(rows)*4} envelope bytes')
