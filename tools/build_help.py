"""Generate retro-readable pages from the unabridged original help text."""
import json, textwrap
from pathlib import Path
source=json.loads(Path('content/launcher-help.json').read_text())
lines={}
for key,paragraphs in source.items():
    rows=[]
    for paragraph in paragraphs:
        clean=paragraph.translate(str.maketrans({'’':"'",'—':'-','…':'...','😏':'~','🐉':'^'})).upper()
        rows.extend(textwrap.wrap(clean,width=54 if key=="story" else 84,break_long_words=False,break_on_hyphens=False))
        if key!='controls' or not any(paragraph.startswith(k) for k in ('DUB ECHO','NOISE','FILTER','CRUSH','BROWSE','BEAT FX','Right Deck','MASTER LEVEL')):rows.append('')
    while rows and not rows[-1]:rows.pop()
    lines[key]=rows
header='/* Generated by tools/build_help.py from content/launcher-help.json. */\n'
for key,rows in lines.items():
    header+='static const char*help_'+key+'[]={\n'+''.join(' '+json.dumps(row)+',\n' for row in rows)+'};\n'
Path('native/help_text.h').write_text(header)
Path('work/help-lines.json').write_text(json.dumps(lines))
print({k:(len(v)+9)//10 for k,v in lines.items()})
