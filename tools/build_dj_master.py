"""Pack the four generated DJ Master poses into a small immutable sprite atlas."""
from pathlib import Path
import re, subprocess
ROOT=Path(__file__).resolve().parent.parent
source=ROOT/'assets/dj-wars/guetta-chibi-v1.png'
# The baton extends into the lower row's gutter; keep its complete silhouette.
cells=['627x627+0+0','627x627+627+0','700x627+0+627','554x627+700+627']
boxes=[]
for cell in cells:
    bounds=subprocess.check_output(['magick',str(source),'-crop',cell,'+repage','-alpha','extract','-threshold','75%','-format','%@','info:']).decode()
    match=re.fullmatch(r'(\d+)x(\d+)\+(\d+)\+(\d+)',bounds)
    assert match,bounds
    boxes.append(tuple(map(int,match.groups())))
W=H=128; COLORS=96
factor=min(120/max(b[0] for b in boxes),120/max(b[1] for b in boxes))
palettes=[];frames=[]
for cell,(bw,bh,bx,by) in zip(cells,boxes):
    rw,rh=max(1,round(bw*factor)),max(1,round(bh*factor))
    rgba=subprocess.check_output(['magick',str(source),'-crop',cell,'+repage','-crop',f'{bw}x{bh}+{bx}+{by}','+repage','-channel','A','-threshold','75%','+channel','-filter','point','-resize',f'{rw}x{rh}!','-background','none','-gravity','south','-extent','128x128','+dither','-colors',str(COLORS),'-depth','8','rgba:-'])
    assert len(rgba)==W*H*4
    palette=[0];lookup={};pixels=[]
    for i in range(0,len(rgba),4):
        r,g,b,a=rgba[i:i+4]
        if a<192:pixels.append(0);continue
        color=(r<<16)|(g<<8)|b
        if color not in lookup:lookup[color]=len(palette);palette.append(color)
        pixels.append(lookup[color])
    assert len(palette)<=COLORS
    palettes.append(palette+[0]*(COLORS-len(palette)));frames.append(pixels)
out='/* Generated by tools/build_dj_master.py. Built-in Imagegen chibi caricature. */\n#ifndef RX3_DJ_MASTER_ATLAS_H\n#define RX3_DJ_MASTER_ATLAS_H\n'
out+='static const unsigned dj_master_palette[4][96]={\n'+''.join('{'+','.join(hex(c) for c in p)+'},\n' for p in palettes)+'};\n'
out+='static const unsigned char dj_master_pixels[4][128*128]={\n'
for pixels in frames:out+='{\n'+''.join(','.join(map(str,pixels[y*W:(y+1)*W]))+',\n' for y in range(H))+'},\n'
out+='};\n#endif\n'
(ROOT/'shared/dj_master_atlas.h').write_text(out)
print('DJ Master: four poses,',4*128*128+4*96*4,'bytes; no runtime allocation')
