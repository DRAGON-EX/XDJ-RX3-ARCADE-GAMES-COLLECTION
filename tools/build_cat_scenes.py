"""Pack supplied artwork into a small indexed atlas for ARM and WASM.

Only downsampling/colour packing; originals remain in assets/cats. All animation
is done by the shared renderer without decoded full-resolution images or a GIF.
"""
from pathlib import Path
import subprocess

sources = sorted(Path('assets/cats').glob('[0-9][0-9]-*.png'))
assert len(sources) == 10
sources.append(Path('assets/music/no-cover-cat.gif'))
palettes, sprites = [], []
for path in sources:
    rgba = subprocess.check_output(['magick', str(path) + ('[0]' if path.suffix == '.gif' else ''),
        '-filter', 'point', '-resize', '128x128!', '+dither', '-colors', '128',
        '-depth', '8', 'rgba:-'])
    assert len(rgba) == 128 * 128 * 4
    palette, lookup, indices = [0], {}, []
    for i in range(0, len(rgba), 4):
        r, g, b, a = rgba[i:i+4]
        if a < 128:
            indices.append(0)
            continue
        rgb = (r << 16) | (g << 8) | b
        if rgb not in lookup:
            lookup[rgb] = len(palette)
            palette.append(rgb)
        indices.append(lookup[rgb])
    assert len(palette) <= 256
    palettes.append(palette + [0] * (256-len(palette)))
    sprites.append(indices)

out = '/* Generated by tools/build_cat_scenes.py from user-supplied artwork. */\n'
out += '#define CAT_ATLAS_COUNT 11\n#define CAT_ATLAS_SIZE 128\n'
out += 'static const unsigned cat_palette[11][256]={\n'
out += ''.join('{' + ','.join(hex(c) for c in p) + '},\n' for p in palettes) + '};\n'
out += 'static const unsigned char cat_pixels[11][128*128]={\n'
out += ''.join('{' + ','.join(map(str, p)) + '},\n' for p in sprites) + '};\n'
Path('shared/cat_atlas.h').write_text(out)
print('Cat atlas:', len(sprites), 'sprites,', 11*(128*128+256*4), 'bytes, no runtime allocation')
